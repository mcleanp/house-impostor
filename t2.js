const { open, sleep, send } = require('./w.js');
const R = 'T' + Math.random().toString(36).slice(2, 5).toUpperCase();
(async () => {
  const D = await open(R, 'Dir', true);
  const socks = [];
  for (const n of ['Cuba', 'Debra', 'Eve']) socks.push(await open(R, n, false));
  await sleep(400);
  send(socks[0], { t: 'start', level: 'house' });
  await sleep(800);
  const people = D.snap.people || [];
  const byId = Object.fromEntries(socks.map((s) => [s.id, s]));
  const imp = people.find((p) => p.role === 'impostor');
  const crew = people.filter((p) => p.role === 'crew');
  for (const s of socks) send(s, { t: 'move', room: 'room' });
  await sleep(600);
  await sleep(15500);
  const victim = byId[crew[0].id];
  const before = victim.msgs.length;
  send(byId[imp.id], { t: 'kill', victim: crew[0].id, kind: 'delay' });
  await sleep(400);
  const during = victim.msgs.slice(before);
  console.log('victim got at kill time:', JSON.stringify(during.map((m) => m.t + ':' + (m.text || ''))));
  console.log('victim snapshot marked flag:', victim.snap && victim.snap.you && victim.snap.you.marked);
  await sleep(2500);
  const died = victim.msgs.filter((m) => m.t === 'died').slice(-1)[0];
  console.log('died message:', JSON.stringify(died));
  const impAck = byId[imp.id].msgs.filter((m) => m.t === 'nope').slice(-1)[0];
  console.log('impostor still told:', JSON.stringify(impAck && impAck.text));
  process.exit(0);
})();
